/**
 * Bundles every migration plus the starting content into supabase/setup.sql —
 * one file to paste into the Supabase SQL Editor. All statements are
 * idempotent, so the file can be run again safely (for example after an update).
 *
 *   npm run db:setup-sql
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const migrationsDir = join(root, "supabase", "migrations");
const migrations = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const parts = migrations.map((file) => {
  const sql = readFileSync(join(migrationsDir, file), "utf8").trim();
  return `-- >>> ${file}\n${sql}\n`;
});

const content = readFileSync(join(root, "supabase", "seed", "01_content.sql"), "utf8").trim();

const header = `-- =============================================================================
-- BSBRA Digital Platform — complete database setup
--
-- HOW TO USE
--   Supabase Dashboard → SQL Editor → New query → paste this whole file → Run.
--   Takes a few seconds. Safe to run again: every statement is idempotent.
--
-- WHAT IT CREATES
--   ${migrations.length} migrations (schema, Row Level Security, audit trail, storage, search)
--   + starting content (site settings, bilingual pages, laws & conventions, links).
--
-- NEXT STEPS (see README §2)
--   • Optional demo data for staging: supabase/seed/02_demo_data.sql
--   • Make yourself the Controlling Authority after registering:
--       update public.profiles set role = 'super_admin' where email = 'you@example.org';
--
-- Generated by scripts/build-setup-sql.ts — edit the migrations, not this file.
-- =============================================================================

`;

writeFileSync(join(root, "supabase", "setup.sql"), `${header}${parts.join("\n")}\n-- >>> seed/01_content.sql\n${content}\n`);
console.log(`Wrote supabase/setup.sql (${migrations.length} migrations + starting content)`);
